/**
 * Allows live registration of 3D molecules fetched from PubChem / ChEMBL / ChEBI (Google DeepMind Science Skills)
 */
export function registerDynamicSubstance(newSub: Substance): void {
  if (!SUBSTANCE_BY_ID[newSub.id]) {
    SUBSTANCES.unshift(newSub);
  }
  SUBSTANCE_BY_ID[newSub.id] = newSub;
}

